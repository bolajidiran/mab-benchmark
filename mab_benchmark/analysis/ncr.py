"""
mab_benchmark.analysis.ncr
==========================

Normalised Causal Regret (NCR), Chapter Three, Definition 3.1:

    NCR(pi, T) = R(pi, T) / R_rand(T),     R_rand(T) = sum_t (mu*_t - mean_a mu_{a,t})

R_rand is the expected cumulative regret of the uniform Random policy on the
same environment instance, so NCR = 0 for the oracle and NCR = 1 (in
expectation) for uniform Random, whatever the reward scale, K or T. This is
the normaliser that makes the regret term of the GUF commensurable with the
latency and constraint terms, which already lie on a [0, inf) scale with 0 as
the ideal (Chapter Three, Section 3.5).

In the synthetic settings the arm means are known, so R(pi, T) is the exact
pseudo-regret and R_rand(T) is computed analytically by
environment.expected_random_regret(). On logged data the regret is
interventional (causal) only through the IPS correction of Section 3.9; the
synthetic settings need no correction because the reward of every arm is
generated by the environment, not by a logging policy.
"""

from __future__ import annotations

import numpy as np


def random_regret(EnvClass, env_kwargs: dict, seeds) -> np.ndarray:
    """R_rand(T) for each seed: the environment is rebuilt exactly as the runner builds it."""
    return np.array([EnvClass(**env_kwargs, seed=int(s)).expected_random_regret() for s in seeds],
                    dtype=float)


def ncr(regrets, random_regrets) -> np.ndarray:
    """Per-run NCR, paired by seed. Runs whose instance has R_rand = 0 (all arms
    equal) are undefined and returned as NaN."""
    r = np.asarray(regrets, dtype=float)
    z = np.asarray(random_regrets, dtype=float)
    if r.shape != z.shape:
        raise ValueError("regrets and random_regrets must be paired run by run")
    out = np.full_like(r, np.nan)
    ok = z > 0
    out[ok] = r[ok] / z[ok]
    return out


def ncr_for_setting(regrets, EnvClass, env_kwargs: dict, seeds) -> np.ndarray:
    return ncr(regrets, random_regret(EnvClass, env_kwargs, seeds))
