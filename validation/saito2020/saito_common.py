def raw_log_path(policy: str, campaign: str) -> Path:
    cands = []
    if os.environ.get("OBD_DIR"):
        base = Path(os.environ["OBD_DIR"]) / policy / campaign
        cands += [base / f"{campaign}.csv", base / f"{campaign}.csv.gz"]
    base = REPO / "open_bandit_dataset" / policy / campaign
    cands += [base / f"{campaign}.csv", base / f"{campaign}.csv.gz",
              HERE / "_transfer" / f"{policy}_{campaign}.csv.gz",
              REPO / "obd_preprocessing" / "_transfer" / f"{policy}_{campaign}.csv.gz"]
    for p in cands:
        if p.exists():
            return p
    raise FileNotFoundError(f"No OBD log for {policy}/{campaign}; looked in: " +
                            ", ".join(str(c) for c in cands))


def cache_path(policy: str, campaign: str) -> Path:
    return CACHE_DIR / f"log_{policy}_{campaign}.npz"


def load_cache(policy: str, campaign: str) -> dict:
    p = cache_path(policy, campaign)
    if not p.exists():
        raise SystemExit(f"{p} missing: run s0_prepare_logs.py first")
    d = dict(np.load(p, allow_pickle=False))
    d["vocab_sizes"] = [int(x) for x in d["vocab_sizes"]]
    return d


def one_hot_context(d: dict, rows: np.ndarray | slice) -> np.ndarray:
    """User context exactly as obp builds it: pd.get_dummies(user_feature_0..3,
    drop_first=True) over the full log, categories in sorted order. Codes in
    the cache are ranks in that sorted vocabulary, so code 0 is the dropped
    category."""
    codes = d["user_codes"][rows]
    sizes = d["vocab_sizes"]
    n = codes.shape[0]
    X = np.zeros((n, sum(s - 1 for s in sizes)), dtype=np.uint8)
    off = 0
    for f, s in enumerate(sizes):
        k = codes[:, f].astype(np.int64)
        m = k > 0
        X[np.flatnonzero(m), off + k[m] - 1] = 1
        off += s - 1
    return X


def seed_table(n: int = 30) -> list[int]:
    """Pre-registered seeds of the package (1000 to 1029), so that the replay
    test uses the same seeds as S4. Falls back to the documented values if
    the package is not importable."""
    try:
        sys.path.insert(0, str(REPO))
        from mab_benchmark.runner import SEED_TABLE
        return list(SEED_TABLE[:n])
    except Exception:
        return list(range(1000, 1000 + n))


def wilson(k: int, n: int, z: float = 1.959963984540054):
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return c - h, c + h


def md5_of(path: Path, block: int = 1 << 24) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        while chunk := f.read(block):
            h.update(chunk)
    return h.hexdigest()


def environment_info() -> dict:
    import pandas, scipy, sklearn
    return {"python": sys.version.split()[0], "platform": platform.platform(),
            "numpy": np.__version__, "pandas": pandas.__version__,
            "scipy": scipy.__version__, "scikit-learn": sklearn.__version__}


def _default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, Path):
        return str(o)
    raise TypeError(type(o))


def write_json(obj, path: Path) -> None:
    path.write_text(json.dumps(obj, indent=2, default=_default), encoding="utf-8")
